    class mobil extends MenuDataMobil {
       String kode_mobil, merk, type, warna;
        int harga;

        public mobil() {
            this.kode_mobil = textkode.getText();
            this.merk = textmerk.getText();
            this.type = texttype.getText();
            this.warna = textwarna.getText();
            this.harga = Integer.parseInt(textharga.getText());
        }
    }
    
        public void TampilTabel() {
        model = new DefaultTableModel();
        model.addColumn("Kode");
        model.addColumn("Merk");
        model.addColumn("Type");
        model.addColumn("Wrna");
        model.addColumn("Harga");
        tblmobil.setModel(model);

        try {
            this.stat = k.getCon().prepareStatement("Select * From mobil");
            this.rs = this.stat.executeQuery();
            while (rs.next()) {
                Object[] data = {
                    rs.getString(1),
                    rs.getString(2),
                    rs.getString(3),
                    rs.getString(4),
                    rs.getInt(5)
                };
                model.addRow(data);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(null, e.getMessage());
        }
        lblharga.setText("");
    }



