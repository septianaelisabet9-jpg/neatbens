    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        if (textktp.getSelectedItem() == null || textkodemobil.getSelectedItem() == null) {
    javax.swing.JOptionPane.showMessageDialog(null, "Pilih KTP dan Kode Mobil terlebih dahulu!");
    return;
}

String ktp = textktp.getSelectedItem().toString();
String kodeMobil = textkodemobil.getSelectedItem().toString();
        try {
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
            String tanggal = sdf.format(jCalendarComboBox2.getDate());
            
            this.stat = k.getCon().prepareStatement("insert into beli_cash values(?,?,?,?,?)");
            stat.setString(1, textkodecash.getText());
            stat.setString(2, textktp.getSelectedItem().toString());
            stat.setString(3, textkodemobil.getSelectedItem().toString());
            stat.setString(4, tanggal);
            stat.setString(5, textbayar.getText());
            stat.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
            Tampiltabel();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnUbahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUbahActionPerformed
        if (textktp.getSelectedItem() == null || textkodemobil.getSelectedItem() == null) {
    javax.swing.JOptionPane.showMessageDialog(null, "Pilih KTP dan Kode Mobil terlebih dahulu!");
    return;
}

String ktp = textktp.getSelectedItem().toString();
String kodeMobil = textkodemobil.getSelectedItem().toString();
        try {
            java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("yyyy-MM-dd");
            String tanggal = sdf.format(jCalendarComboBox2.getDate());
            
            this.stat = k.getCon().prepareStatement("update beli_cash set ktp=?, kode_mobil=?, tgl_bayar=?, cash_tgl=? where kode_cash=?");
            stat.setString(1, textktp.getSelectedItem().toString());
            stat.setString(2, textkodemobil.getSelectedItem().toString());
            stat.setString(3, tanggal);
            stat.setString(4, textbayar.getText());
            stat.setString(5, textkodecash.getText());
            stat.executeUpdate();
            javax.swing.JOptionPane.showMessageDialog(null, "Data berhasil diubah");
            Tampiltabel();
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }//GEN-LAST:event_btnUbahActionPerformed

