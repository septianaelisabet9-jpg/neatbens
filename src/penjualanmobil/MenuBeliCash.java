        textktp.setSelectedItem(model.getValueAt(row, 1).toString());
        textkodemobil.setSelectedItem(model.getValueAt(row, 2).toString());
        textbayar.setText(model.getValueAt(row, 4).toString());
        // Jika ingin otomatis mengisi tanggal dari tabel ke jCalendarComboBox2:
