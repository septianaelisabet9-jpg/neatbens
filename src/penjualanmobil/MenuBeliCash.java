    public void Tampiltabel() {
        model = new javax.swing.table.DefaultTableModel();
        model.addColumn("Kode Cash");
        model.addColumn("No KTP");
        model.addColumn("Kode Mobil");
        model.addColumn("Tanggal Beli");
        model.addColumn("Bayar");
        tblbelicash.setModel(model);
        try {
            this.stat = k.getCon().prepareStatement("select * from beli_cash");
            this.rs = this.stat.executeQuery();
            while (rs.next()) {
                Object[] data = {
                    rs.getString(1),
                    rs.getString(2),
                    rs.getString(3),
                    rs.getString(4),
                    rs.getString(5)
                };
                model.addRow(data);
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

    public void tampilKTP() {
        try {
            this.stat = k.getCon().prepareStatement("select ktp from pembeli");
            this.rs = this.stat.executeQuery();
            textktp.removeAllItems();
            while (rs.next()) {
                textktp.addItem(rs.getString("ktp"));
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

    public void tampilMobil() {
        try {
            this.stat = k.getCon().prepareStatement("select kode_mobil from mobil");
            this.rs = this.stat.executeQuery();
            textkodemobil.removeAllItems();
            while (rs.next()) {
                textkodemobil.addItem(rs.getString("kode_mobil"));
            }
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(null, e.getMessage());
        }
    }

